task clear_inputs;
begin for(i=0;i<64;i=i+1) begin in_pkt[i]=0; in_wr[i]=0; end end
endtask

function [`PACKET_WIDTH-1:0] pkt;
input integer sc,sp,dc,dp;
input [31:0] payload;
integer sr,scol,dr,dcol;
begin
 sr=sp/4; scol=sp%4; dr=dp/4; dcol=dp%4;
 pkt={dc[1:0],dr[1:0],dcol[1:0],sc[1:0],sr[1:0],scol[1:0],2'd0,2'd0,payload};
end
endfunction

task one;
input integer s,d,sc,sp,dc,dp;
input [31:0] payload;
reg [`PACKET_WIDTH-1:0] p;
reg pass;
begin
 p=pkt(sc,sp,dc,dp,payload);
 clear_inputs; rst=1; repeat(2) @(posedge clk); rst=0; repeat(2) @(posedge clk);
 in_pkt[s]=p; in_wr[s]=1; @(negedge clk); in_pkt[s]=0; in_wr[s]=0;
 pass=0;
 for(k=0;k<150;k=k+1) begin @(posedge clk); #1; if(out_valid[d]) begin if(out_pkt[d]==p) pass=1; else $display("WRONG d%0d got %h exp %h",d,out_pkt[d],p); k=150; end end
 if(pass) $display("SMOKE PASS C%0d/R%0d -> C%0d/R%0d",sc,sp,dc,dp);
 else $display("SMOKE FAIL C%0d/R%0d -> C%0d/R%0d",sc,sp,dc,dp);
end
endtask

